// File reads use the production controller; navigation metadata is synthetic.
const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path');
async function main(){
 const base=process.env.E2E_BASE_URL,out=process.env.E2E_OUTPUT_DIR;
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage(),errors=[],reads=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('request',r=>{if(r.url().includes('/api/script-hub/results/'))reads.push({path:new URL(r.url()).pathname,range:r.headers().range||null});});
 const file=name=>'/api/script-hub/results/logs/'+name;
 const job={id:'text-log-job',job_id:'text-log-job',module:'profile',status:'completed',progress:100,stage:'完成',detail:'合成结果预览',payload:{_task_name:'日志与文本预览'},outputs:[],created_at:'2026-10-03T00:00:00Z',started_at:'2026-10-03T00:00:01Z',completed_at:'2026-10-03T00:00:03Z'};
 const names=['run.log','large.log','notes.txt','empty.log','retry.log','ignored.log','wrong.log','private.log'];
 const results={success:true,status:'completed',job,outputs:names.map(name=>({kind:'data',label:name,url:file(name),module:'profile'})),assets:[],result:{}};
 const json=(r,body)=>r.fulfill({contentType:'application/json',body:JSON.stringify(body)});
 await page.route('**/api/**',async r=>{
  const p=new URL(r.request().url()).pathname;
  if(p.startsWith('/api/script-hub/results/'))return r.continue();
  let body={success:true};
  if(p==='/api/auth/me')body={auth_mode:'internal',username:'内部验收',role:'user'};
  else if(p==='/api/jobs/modules')body={success:true,modules:[]};
  else if(p==='/api/jobs')body={success:true,jobs:[job],counts:{completed:1},total:1,has_more:false};
  else if(p==='/api/jobs/text-log-job')body={success:true,job};
  else if(p==='/api/jobs/text-log-job/results')body=results;
  else if(p==='/api/jobs/text-log-job/events')return r.fulfill({contentType:'text/event-stream',body:'event: completed\ndata: '+JSON.stringify({job,status:'completed'})+'\n\n'});
  else if(p==='/api/projects')body={success:true,projects:[]};
  return json(r,body);
 });
 await page.goto(base+'/analysis/script-hub/jobs?job=text-log-job');
 await page.getByRole('tab',{name:'结果',exact:true}).click();
 await page.getByRole('tab',{name:'分析详情',exact:true}).click();
 const pre=page.getByLabel('文件原文',{exact:true}),range=page.getByLabel('日志预览范围',{exact:true});
 const select=async name=>{const option=page.getByRole('option',{name:new RegExp(name.replaceAll('.','\\.'))});await page.getByLabel('结果文件',{exact:true}).selectOption(await option.getAttribute('value'));};
 await pre.waitFor();assert.equal(await range.inputValue(),'end');
 let text=await pre.textContent();assert(text.startsWith('日志 0105 '));assert(text.endsWith('日志 2104 样本 001 p=1.00000000001e-9\n'));
 assert.equal(reads.filter(r=>r.path!==file('run.log')).length,0);
 await range.selectOption('start');await page.getByText(/当前显示最前 2000 行/).waitFor();
 text=await pre.textContent();assert(text.startsWith('日志 0000 '));assert(text.endsWith('日志 1999 样本 001 p=1.00000000001e-9\n'));
 await select('large.log');await page.getByText(/仅预览末尾 2 MB/).waitFor();
 text=await pre.textContent();assert(text.startsWith('文'));assert(text.endsWith('末尾完成 001 p=1.00000000001e-9\n'));assert(!text.includes('�'));
 assert((await pre.boundingBox()).height<=401);
 const tailScroll=await pre.evaluate(el=>({top:el.scrollTop,height:el.clientHeight,total:el.scrollHeight}));
 assert(tailScroll.top+tailScroll.height>=tailScroll.total-1,JSON.stringify(tailScroll));
 const tail=await page.request.get(base+file('large.log'),{headers:{Range:'bytes=-2097152'}});
 assert.equal(tail.status(),206);assert.equal((await tail.body()).length,2097152);
 assert.equal(Number(tail.headers()['content-range'].split('/')[1])>3*1024*1024,true);
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'下载完整日志',exact:true}).click()]);
 const downloadPath=await download.path(),full=await page.request.get(base+file('large.log'));
 assert.equal(full.status(),200);assert(full.headers()['content-disposition'].startsWith('attachment'));
 assert.deepEqual(await fs.readFile(downloadPath),await full.body());
 await page.screenshot({path:path.join(out,'desktop-large-log.png')});
 await select('notes.txt');await pre.waitFor();
 await page.waitForFunction(()=>document.querySelector('pre[aria-label="文件原文"]')?.textContent.includes('9007199254740993'));
 text=await pre.textContent();assert(text.includes('001'));assert(text.includes('1.00000000001e-9'));assert(text.includes('<script>window.textExecuted=true</script>'));
 assert.equal(await page.evaluate(()=>window.textExecuted),undefined);assert.equal(await page.getByText(/无法按 JSON/).count(),0);
 const before=reads.length;await page.getByRole('button',{name:'重新读取文本',exact:true}).click();
 await page.getByRole('button',{name:'重新读取文本',exact:true}).waitFor({state:'visible'});
 await page.waitForFunction(()=>document.querySelector('pre[aria-label="文件原文"]')?.textContent.includes('9007199254740993'));assert.equal(reads.length,before+1);
 await page.setViewportSize({width:390,height:844});await pre.scrollIntoViewIfNeeded();await page.screenshot({path:path.join(out,'mobile-text-preview.png')});
 const sizes=await page.evaluate(()=>({width:innerWidth,document:document.documentElement.scrollWidth}));assert(sizes.document<=sizes.width+1,JSON.stringify(sizes));
 await select('empty.log');await page.getByText('日志文件为空。',{exact:true}).waitFor();
 await select('retry.log');await page.getByRole('alert').filter({hasText:'结果文件不存在或已移除'}).waitFor();
 await page.getByRole('button',{name:'重新读取日志',exact:true}).focus();await page.keyboard.press('Enter');
 await page.waitForFunction(()=>document.querySelector('pre[aria-label="文件原文"]')?.textContent.includes('恢复读取 001'));
 await select('ignored.log');await page.getByRole('alert').filter({hasText:'不支持文件末尾预览'}).waitFor();
 await page.screenshot({path:path.join(out,'mobile-range-fallback.png')});
 await range.selectOption('start');await page.getByText(/仅预览前 2 MB/).waitFor();assert((await pre.textContent()).startsWith('HEAD 001'));assert(!(await pre.textContent()).includes('末尾完成'));
 await select('wrong.log');await page.getByRole('alert').filter({hasText:'返回了网页'}).waitFor();
 await select('private.log');await page.getByRole('alert').filter({hasText:'项目权限'}).waitFor();
 // Delayed file response is discarded after selection changes.
 let release;const gate=new Promise(done=>{release=done});
 await page.route('**'+file('run.log'),async r=>{await gate;try{await r.continue();}catch(e){if(!r.request().failure())throw e;}});
 await select('run.log');await page.getByText('正在读取日志…',{exact:true}).waitFor();
 await select('notes.txt');await page.waitForFunction(()=>document.querySelector('pre[aria-label="文件原文"]')?.textContent.includes('9007199254740993'));
 release();await page.unroute('**'+file('run.log'));
 await page.reload();await page.getByRole('tab',{name:'结果',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('pre[aria-label="文件原文"]')?.textContent.includes('9007199254740993'));
 assert((await page.getByLabel('结果文件',{exact:true}).inputValue()).includes('notes.txt'));assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(out,'browser-summary.json'),JSON.stringify({passed:true,realFileController:true,tailBytes:2097152,fullDownloadBytes:(await full.body()).length,utf8Boundary:true,lineLimit:2000,rangeFallback:true,missingRetry:true,empty:true,permissions:true,htmlRejected:true,lateResponseDiscarded:true,refreshSelection:true,sizes,errors,reads},null,2));
 await browser.close();console.log(JSON.stringify({passed:true,sizes,errors,reads:reads.length}));
}
main().catch(e=>{console.error(e);process.exit(1)});
