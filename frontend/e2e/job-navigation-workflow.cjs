// Real read-only task APIs with synthetic snapshots. Use only the isolated fixture.
const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path');
async function main(){
 const base=process.env.E2E_BASE_URL,out=process.env.E2E_OUTPUT_DIR;
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:390,height:844}}),page=await context.newPage(),errors=[],mutations=[],requests=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('request',r=>{requests.push({method:r.method(),path:new URL(r.url()).pathname});if(new URL(r.url()).pathname.startsWith('/api/')&&!['GET','HEAD'].includes(r.method()))mutations.push(r.method()+' '+r.url());});
 await page.route('**/api/auth/me',r=>r.fulfill({contentType:'application/json',body:'{"auth_mode":"internal","username":"内部验收","role":"user"}'}));
 await page.route('**/api/jobs/modules',r=>r.fulfill({contentType:'application/json',body:'{"success":true,"modules":[]}'}));
 const query=new URLSearchParams({status:'completed',q:'手机导航',offset:'0'});
 const list=page.getByRole('region',{name:'任务列表',exact:true}),detail=page.getByRole('region',{name:'任务详情',exact:true});
 const checkbox=list.getByRole('checkbox',{name:'选择任务 job-navigation-035',exact:true});
 const row=page.locator('.job-row').filter({has:page.getByRole('checkbox',{name:'选择任务 job-navigation-035',exact:true})});
 const open=row.getByRole('button',{name:'查看任务详情',exact:true});
 await page.goto(base+'/analysis/script-hub/jobs?'+query);
 await checkbox.waitFor();assert.equal(await list.locator('.job-row').count(),50);await checkbox.check();
 await row.getByText('手机导航任务 035',{exact:true}).waitFor();
 await open.focus();await page.keyboard.press('Enter');await detail.getByRole('tab',{name:'配置',exact:true}).waitFor();
 assert.equal(await list.isVisible(),false);assert.equal(await page.locator('.job-monitor-overview').isVisible(),false);
 assert.equal(await detail.evaluate(el=>el===document.activeElement),true);
 await detail.getByRole('heading',{name:'手机导航任务 035',exact:true}).waitFor();
 await detail.getByRole('tab',{name:'配置',exact:true}).click();
 await detail.getByText('指标分组表.csv',{exact:true}).waitFor();
 const sizes=await page.evaluate(()=>({width:innerWidth,document:document.documentElement.scrollWidth}));
 assert(sizes.document<=sizes.width+1,JSON.stringify(sizes));
 const position=await detail.boundingBox();assert(position.y>=-1&&position.y<100,JSON.stringify(position));
 await page.screenshot({path:path.join(out,'mobile-task-detail.png')});
 await detail.getByRole('tab',{name:'配置',exact:true}).focus();
 const originalFocus=await page.evaluate(()=>document.activeElement?.textContent),scrollY=await page.evaluate(()=>window.scrollY);
 await page.waitForResponse(r=>new URL(r.url()).pathname==='/api/jobs'&&r.request().method()==='GET',{timeout:10000});
 assert.equal(await page.evaluate(()=>document.activeElement?.textContent),originalFocus);
 assert(Math.abs(await page.evaluate(()=>window.scrollY)-scrollY)<3);
 await detail.getByRole('button',{name:'返回任务列表',exact:true}).click();
 assert.equal(await open.evaluate(el=>el===document.activeElement),true);assert.equal(await checkbox.isChecked(),true);
 let current=new URL(page.url()).searchParams;assert.equal(current.has('job'),false);
 for(const [key,value] of query)assert.equal(current.get(key),value);
 await page.screenshot({path:path.join(out,'mobile-return-to-list.png')});
 // Closing before an actual detail response arrives must not reopen the task.
 let release;const gate=new Promise(done=>{release=done});
 const gatedPath=/\/api\/jobs\/job-navigation-035(?:\/events)?$/;
 await page.route(gatedPath,async route=>{await gate;try{await route.continue();}catch(error){if(!route.request().failure())throw error;}});
 query.set('offset','50');query.set('job','job-navigation-035');
 await page.goto(base+'/analysis/script-hub/jobs?'+query);
 await detail.getByText('正在读取任务详情…',{exact:true}).waitFor();
 await page.screenshot({path:path.join(out,'mobile-loading-detail.png')});
 await detail.getByRole('button',{name:'返回任务列表',exact:true}).click();
 const received=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/jobs/job-navigation-035');
 const start=requests.length;release();assert.equal((await received).status(),200);await page.unroute(gatedPath);
 await list.waitFor();assert.equal(await detail.isVisible(),false);assert.equal(new URL(page.url()).searchParams.has('job'),false);
 assert.equal(requests.slice(start).filter(r=>r.path==='/api/jobs/job-navigation-035/results').length,0);
 assert.equal(await list.evaluate(el=>el===document.activeElement),true);
 // Refresh and resize retain the same selected task and tab; only the layout changes.
 query.set('job','job-navigation-035');
 await page.goto(base+'/analysis/script-hub/jobs?'+query);
 await detail.getByRole('tab',{name:'配置',exact:true}).waitFor();await detail.getByRole('tab',{name:'配置',exact:true}).click();
 await page.reload();await detail.getByRole('heading',{name:'手机导航任务 035',exact:true}).waitFor();
 await detail.getByRole('tab',{name:'配置',exact:true}).click();
 await page.setViewportSize({width:1440,height:1000});await list.waitFor();await page.locator('.job-monitor-overview').waitFor();
 assert.equal(await detail.getByRole('tab',{name:'配置',exact:true}).getAttribute('aria-selected'),'true');
 assert.equal(await detail.getByRole('button',{name:'返回任务列表',exact:true}).isVisible(),false);
 assert.equal(await page.getByRole('region',{name:'任务配置摘要',exact:true}).count(),1);
 await page.waitForFunction(()=>{const a=document.querySelector('.job-monitor-list').getBoundingClientRect(),b=document.querySelector('.job-monitor-details').getBoundingClientRect();return a.width>0&&b.width>0&&b.left>=a.right-1;},{},{timeout:3000});
 await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(animation=>animation instanceof CSSTransition&&animation.transitionProperty==='width').map(animation=>animation.finished.catch(()=>{})));});
 const desktop=await page.evaluate(()=>({list:document.querySelector('.job-monitor-list').getBoundingClientRect().toJSON(),detail:document.querySelector('.job-monitor-details').getBoundingClientRect().toJSON()}));
 assert(desktop.detail.x>desktop.list.x+desktop.list.width-1,JSON.stringify(desktop));
 await page.screenshot({path:path.join(out,'desktop-task-panels.png')});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await list.isVisible(),false);assert.equal(await detail.getByRole('tab',{name:'配置',exact:true}).getAttribute('aria-selected'),'true');
 await detail.getByRole('button',{name:'关闭任务详情',exact:true}).click();await list.waitFor();
 current=new URL(page.url()).searchParams;assert.equal(current.get('offset'),'50');assert.equal(current.get('q'),'手机导航');assert.equal(current.get('status'),'completed');
 // Missing task is a real 404, with a visible error and a route back.
 query.set('job','nonexistent-navigation-job');
 await page.goto(base+'/analysis/script-hub/jobs?'+query);
 await detail.getByText('任务信息读取失败',{exact:true}).waitFor();
 await detail.getByRole('button',{name:'重新读取任务',exact:true}).waitFor();
 await detail.getByText('无法找到该任务，请返回任务列表核对。',{exact:true}).waitFor();
 assert.equal(await detail.getByText('Job not found',{exact:true}).count(),0);
 const missingPath='/api/jobs/nonexistent-navigation-job',readsBefore=requests.filter(r=>r.path===missingPath).length;
 const reread=page.waitForResponse(r=>new URL(r.url()).pathname===missingPath);
 await detail.getByRole('button',{name:'重新读取任务',exact:true}).click();assert.equal((await reread).status(),404);
 await detail.getByText('无法找到该任务，请返回任务列表核对。',{exact:true}).waitFor();
 assert.equal(requests.filter(r=>r.path===missingPath).length,readsBefore+1);
 await page.waitForFunction(()=>!document.querySelector('.job-monitor-details').textContent.includes('任务状态连接已断开。'));
 const streamsBefore=requests.filter(r=>r.path===missingPath+'/events').length;
 await page.waitForResponse(r=>new URL(r.url()).pathname==='/api/jobs'&&r.request().method()==='GET',{timeout:10000});
 assert.equal(requests.filter(r=>r.path===missingPath+'/events').length,streamsBefore);
 await page.screenshot({path:path.join(out,'mobile-missing-task.png')});
 await detail.getByRole('button',{name:'返回任务列表',exact:true}).click();await list.waitFor();
 assert.equal(new URL(page.url()).searchParams.has('job'),false);
 const actual=await (await page.request.get(base+'/api/jobs/job-navigation-035')).json();
 assert.equal(actual.job.payload._task_name,'手机导航任务 035');assert.equal(actual.job.payload.selected_samples.length,12);
 assert.deepEqual(errors,[]);assert.deepEqual(mutations,[]);
 await fs.writeFile(path.join(out,'browser-summary.json'),JSON.stringify({scope:'real read-only task APIs; synthetic 55-job list',firstPage:50,filtersAndPageRetained:true,selectionAndFocusRetained:true,keyboardOpen:true,lateResponseIgnored:true,refreshAndResponsiveTabPreserved:true,realMissingTask:true,missingRetryFeedback:true,missingSseStopped:true,pollingDoesNotMoveFocus:true,sizes,errors,mutations},null,2));
 await browser.close();console.log(JSON.stringify({passed:true,sizes,errors,mutations}));
}
main().catch(e=>{console.error(e);process.exit(1)});
