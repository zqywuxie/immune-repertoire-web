// Production frontend and Script Hub file endpoint; synthetic documents, no analysis.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
async function main(){
 const base=process.env.E2E_BASE_URL,output=process.env.E2E_OUTPUT_DIR;
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage(),errors=[],reads=[],consoleErrors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',e=>{if(e.type()==='error')consoleErrors.push(e.text());});
 page.on('request',r=>{const p=new URL(r.url()).pathname;if(p.includes('/results/report/'))reads.push({path:p,method:r.method()});});
 const id='document-preview-fixture',job={id,job_id:id,module:'profile',status:'completed',stage:'分析完成',progress:100,created_at:'2026-10-03T00:00:00Z'};
 const folder='/api/script-hub/results/report/';
 const outputs=[['html','可重试的交互报告','retry.html'],['html','请求方式回退报告','fallback.html'],['html','空报告','empty.html'],['html','权限受限报告','private.html'],['pdf','文档预览','document.pdf'],['pdf','文档错误网页','wrong.pdf']].map(([kind,label,name])=>({kind,label,url:folder+name}));
 await page.route('**/api/**',async route=>{
  const p=new URL(route.request().url()).pathname;
  if(p.startsWith(folder))return route.continue();
  let body={success:true};
  if(p==='/api/auth/me')body={auth_mode:'internal',username:'内部验证',role:'user'};
  else if(p==='/api/projects')body={success:true,projects:[]};
  else if(p==='/api/jobs/modules')body={success:true,modules:[]};
  else if(p==='/api/jobs')body={success:true,jobs:[job],counts:{completed:1},total:1,has_more:false};
  else if(p==='/api/jobs/'+id)body={success:true,job};
  else if(p==='/api/jobs/'+id+'/results')body={success:true,job,status:'completed',outputs,assets:[],result:{}};
  else if(p==='/api/jobs/'+id+'/events')return route.fulfill({contentType:'text/event-stream',body:'event: completed\ndata: '+JSON.stringify({job,status:'completed'})+'\n\n'});
  await route.fulfill({contentType:'application/json',body:JSON.stringify(body)});
 });
 await page.goto(base+'/analysis/script-hub/jobs?job='+id);
 await page.getByRole('alert').filter({hasText:'结果文件不存在或已移除'}).waitFor();
 assert.equal(await page.locator('iframe[data-result-document]').count(),0);
 assert.equal(reads.filter(r=>r.path.endsWith('retry.html')&&r.method==='GET').length,0);
 await page.getByRole('button',{name:'重新加载',exact:true}).click();
 let frame=page.frameLocator('iframe[data-result-document="html"]');
 await frame.getByText('合成报告：界面验收',{exact:true}).waitFor();
 await frame.getByRole('button',{name:'仅显示研究组'}).click();
 await frame.getByText('当前显示研究组',{exact:true}).waitFor();
 await frame.getByText(/1.00000000001e-9/).waitFor();
 const downloadPromise=page.waitForEvent('download');
 await frame.getByRole('link',{name:'下载原始数据'}).click();
 const download=await downloadPromise;
 const downloadPath=path.join(output,'report-values.csv');await download.saveAs(downloadPath);
 assert((await fs.readFile(downloadPath,'utf8')).includes('001,研究组,1.00000000001e-9'));
 assert.equal(await page.getByRole('link',{name:'在新标签页查看报告',exact:true}).getAttribute('href'),folder+'retry.html');
 await page.screenshot({path:path.join(output,'desktop-report.png'),fullPage:true});
 await page.getByRole('button',{name:/^空报告/}).click();await page.getByRole('alert').filter({hasText:'报告文件为空'}).waitFor();
 await page.getByRole('button',{name:/^权限受限报告/}).click();await page.getByRole('alert').filter({hasText:'项目权限'}).waitFor();
 await page.getByRole('button',{name:/^请求方式回退报告/}).click();
 frame=page.frameLocator('iframe[data-result-document="html"]');
 await frame.getByText('合成报告：界面验收',{exact:true}).waitFor();
 assert(reads.some(r=>r.path.endsWith('fallback.html')&&r.method==='HEAD'));
 assert(reads.filter(r=>r.path.endsWith('fallback.html')&&r.method==='GET').length>=2);
 await page.getByRole('button',{name:/^文档错误网页/}).click();await page.getByRole('alert').filter({hasText:'未返回 PDF 文档'}).waitFor();
 assert.equal(await page.locator('iframe[data-result-document]').count(),0);
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(output,'mobile-document-error.png'),fullPage:true});
 await page.getByRole('button',{name:/^文档预览/}).click();
 const pdfSupported=await page.evaluate(()=>navigator.pdfViewerEnabled);
 if(pdfSupported!==false)await page.locator('iframe[data-result-document="pdf"]').waitFor();
 else await page.getByText(/当前浏览器不支持内嵌 PDF/).waitFor();
 const pdf=await page.request.get(base+folder+'document.pdf');
 assert.equal(pdf.status(),200);assert(pdf.headers()['content-disposition'].startsWith('inline;'));
 assert((await pdf.body()).subarray(0,5).equals(Buffer.from('%PDF-')));
 const explicit=await page.request.get(base+folder+'document.pdf?download=1');
 assert(explicit.headers()['content-disposition'].startsWith('attachment;'));
 assert((await explicit.body()).equals(await pdf.body()));
 const sizes=await page.evaluate(()=>({width:innerWidth,document:document.documentElement.scrollWidth}));
 assert(sizes.document<=sizes.width+1,JSON.stringify(sizes));
 if(pdfSupported!==false){
 await page.locator('iframe[data-result-document="pdf"]').scrollIntoViewIfNeeded();
 // A focused diagnostic after the native viewer initializes; the PDF engine is browser-owned.
 await page.waitForTimeout(3000);
 const frames=page.frames().map(f=>f.url());
 await fs.writeFile(path.join(output,'pdf-viewer-frames.json'),JSON.stringify(frames,null,2));
 await page.screenshot({path:path.join(output,'mobile-document.png'),fullPage:true});
 await page.locator('iframe[data-result-document="pdf"]').screenshot({path:path.join(output,'pdf-viewer.png')});
 } else await page.screenshot({path:path.join(output,'mobile-document.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(output,'browser-summary.json'),JSON.stringify({scope:'production frontend + real file endpoint; synthetic documents only',pdf_supported:pdfSupported,metadata_checks:true,retry:true,report_scripts:true,report_download:true,head_fallback:true,empty_and_access_errors:true,pdf_inline:true,explicit_download:true,sizes,reads,errors,consoleErrors},null,2));
 await browser.close();console.log(JSON.stringify({passed:true,pdfSupported,sizes,errors}));
}
main().catch(e=>{console.error(e);process.exit(1)});
