// Real job/detail/retry/results/SSE endpoints, production frontend; synthetic executor only.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
async function main(){
 const base=process.env.E2E_BASE_URL,out=process.env.E2E_OUTPUT_DIR;
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage(),errors=[],retryRequests=[],unexpectedResponses=[];
 page.on('response',r=>{const p=new URL(r.url()).pathname;if(p.startsWith('/api/jobs') && r.status()>=400 && !p.endsWith('/job-original/retry'))unexpectedResponses.push({path:p,status:r.status()});});
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('request',r=>{if(new URL(r.url()).pathname.endsWith('/job-original/retry'))retryRequests.push(r.method());});
 await page.route('**/api/auth/me',r=>r.fulfill({contentType:'application/json',body:JSON.stringify({auth_mode:'internal',username:'内部验收',role:'user'})}));
 await page.route('**/api/projects',r=>r.fulfill({contentType:'application/json',body:'{"projects":[]}'}));
 await page.route('**/api/jobs/modules',r=>r.fulfill({contentType:'application/json',body:'{"success":true,"modules":[]}'}));
 await page.goto(base+'/analysis/script-hub/jobs?status=failed&job=job-original');
 await page.getByText('最后记录进度：35%',{exact:true}).waitFor();
 const progress=page.locator('.job-progress-panel');
 const failureColor=await progress.locator('.job-progress-error strong').evaluate(el=>getComputedStyle(el).color);
 assert.equal(await page.locator('.job-row [role=progressbar] > div').evaluate(el=>getComputedStyle(el).backgroundColor),failureColor);
 assert.equal(await progress.locator('details[open]').count(),0);
 assert.equal(await progress.locator('.job-progress-records ol > li').count(),20);
 const records=progress.locator('summary').filter({hasText:'进度记录'});
 await records.focus();await page.keyboard.press('Enter');
 assert.equal(await progress.locator('details[open]').count(),1);
 const history=progress.locator('ol');assert((await history.evaluate(el=>el.clientHeight))<=320);
 const technical=progress.locator('summary').filter({hasText:'错误与技术详情'});
 await technical.focus();await page.keyboard.press('Enter');
 await progress.getByText(/ValueError: 合成输入缺少对照组/).waitFor();
 assert.equal(await progress.locator('pre').first().evaluate(el=>getComputedStyle(el).whiteSpace),'pre-wrap');
 assert.equal(await progress.locator('dd').first().evaluate(el=>getComputedStyle(el).whiteSpace),'pre-wrap');
 assert.equal(await page.getByText('任务状态连接已断开。',{exact:true}).count(),0);
 await page.screenshot({path:path.join(out,'desktop-failure.png'),fullPage:true});
 await page.locator('.job-row').getByRole('button',{name:'重试任务'}).click();
 await page.getByText('当前队列暂不可用，请稍后重试。',{exact:true}).waitFor();
 assert.equal(new URL(page.url()).searchParams.get('job'),'job-original');
 let state=await (await page.request.get(base+'/__fixture/state')).json();
 assert.equal(state.created.length,0);assert.equal(state.original.progress,35);
 await page.locator('.job-row').getByRole('button',{name:'重试任务'}).click();
 await page.waitForURL(url=>url.searchParams.get('job')!=='job-original');
 const freshId=new URL(page.url()).searchParams.get('job');
 assert(freshId.startsWith('job_'));assert.equal(new URL(page.url()).searchParams.get('status'),'failed');
 await progress.locator('.job-progress-percentage').getByText('40%',{exact:true}).waitFor();
 state=await (await page.request.get(base+'/__fixture/state')).json();
 assert.equal(state.created.length,1);assert.equal(state.created[0].job_id,freshId);
 assert.equal(state.created[0].payload.retry_of,'job-original');
 assert.equal(state.original.status,'failed');assert.equal(state.original.progress,35);
 assert.equal(state.created[0].payload.file_id,state.original.payload.file_id);
 assert.equal(await progress.locator('details[open]').count(),0);
 await page.reload();await progress.locator('.job-progress-percentage').getByText('40%',{exact:true}).waitFor();
 assert.equal(new URL(page.url()).searchParams.get('job'),freshId);
 assert.equal(retryRequests.length,2); // no POST on reload
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,'mobile-running.png'),fullPage:true});
 const sizes=await page.evaluate(()=>({width:innerWidth,document:document.documentElement.scrollWidth}));
 assert(sizes.document<=sizes.width+1,JSON.stringify(sizes));
 await page.request.post(base+'/__fixture/release');
 const results=page.getByRole('tab',{name:'结果',exact:true});
 await results.waitFor();await page.waitForFunction(()=>document.querySelector('[role="tab"][aria-selected="true"]')?.textContent?.includes('结果'));
 const final=await (await page.request.get(base+'/api/jobs/'+freshId)).json();
 assert.equal(final.job.status,'completed');assert.equal(final.job.progress,100);
 const old=await (await page.request.get(base+'/api/jobs/job-original')).json();assert.equal(old.job.status,'failed');assert.equal(old.job.progress,35);
 await page.getByRole('tab',{name:'进度',exact:true}).click();await progress.locator('.job-progress-percentage').getByText('100%',{exact:true}).waitFor();
 const elapsed=await progress.locator('[data-job-elapsed]').textContent();
 await page.reload();await page.getByRole('tab',{name:'进度',exact:true}).click();assert.equal(await progress.locator('[data-job-elapsed]').textContent(),elapsed);
 await page.goto(base+'/analysis/script-hub/jobs?job=job-missing-time');
 await page.getByText('最后记录进度：25%',{exact:true}).waitFor();await page.getByText('未记录开始时间',{exact:true}).waitFor();
 await page.getByText('最后记录阶段',{exact:true}).waitFor();
 assert.equal(await progress.locator('.job-progress-heading p').textContent(),'已中断');
 await page.screenshot({path:path.join(out,'mobile-missing-time.png'),fullPage:true});
 assert.deepEqual(errors,[]);assert.deepEqual(unexpectedResponses,[]);
 await fs.writeFile(path.join(out,'browser-summary.json'),JSON.stringify({scope:'real Flask APIs and background service; synthetic executor only',failureProgress:35,newJobId:freshId,retryPosts:retryRequests.length,retryFailure:true,originalRetained:true,sameInputs:true,urlAndReload:true,collapsedRecords:true,historyBound:20,keyboard:true,elapsedFrozen:elapsed,missingTime:true,sizes,errors,unexpectedResponses},null,2));
 await browser.close();console.log(JSON.stringify({passed:true,freshId,elapsed,sizes,errors}));
}
main().catch(e=>{console.error(e);process.exit(1)});
